const assert=require('node:assert/strict');
const {fixture}=require('./operacao.fixture.cjs');
async function main(){
  const f=await fixture();const {admin,motorista,outro,familia,familiaB,a,b,rota,data,confirmar}=f;
  assert.equal((await confirmar(familia.cliente,b.id,'IDA')).status,404);
  const proprios=await(await familia.cliente.request('/operacao/familia/alunos')).json();
  assert.ok(proprios.some(x=>x.id===a.id)&&!proprios.some(x=>x.id===b.id));
  for(const [u,aluno] of [[familia,a],[familiaB,b]]) for(const trajeto of ['IDA','VOLTA']) assert.equal((await confirmar(u.cliente,aluno.id,trajeto)).status,204);
  assert.equal((await confirmar(familia.cliente,a.id,'IDA','CANCELADO')).status,204);
  let agenda=await(await familia.cliente.request('/operacao/agenda?data='+data)).json();
  assert.equal(agenda.find(x=>x.aluno_id===a.id&&x.trajeto==='IDA').status,'CANCELADO');
  assert.equal(agenda.find(x=>x.aluno_id===a.id&&x.trajeto==='VOLTA').status,'CONFIRMADO');
  await confirmar(familia.cliente,a.id,'IDA');
  const iniciar=()=>motorista.cliente.request('/operacao/viagens','POST',{rotaId:rota.id,trajeto:'IDA'});
  assert.equal((await outro.cliente.request('/operacao/viagens','POST',{rotaId:rota.id,trajeto:'IDA'})).status,404);
  assert.equal((await iniciar()).status,409,'Excesso de capacidade deve impedir início');
  assert.equal((await admin.request('/veiculos/'+f.veiculo.id,'PUT',{placa:f.veiculo.placa,modelo:f.veiculo.modelo,capacidade:2,motoristaId:f.m.id})).status,200);
  const started=await iniciar();assert.equal(started.status,200);let viagem=await started.json();const id=viagem.id;
  assert.equal(viagem.alunos.length,2);
  assert.equal((await admin.request('/veiculos/'+f.veiculo.id,'PUT',{placa:f.veiculo.placa,modelo:f.veiculo.modelo,capacidade:1,motoristaId:f.m.id})).status,409,'Veículo em viagem não pode ser alterado');
  assert.equal((await(await iniciar()).json()).id,id,'Repetir início não cria outra viagem');
  assert.equal((await confirmar(familia.cliente,a.id,'IDA','CANCELADO')).status,409);
  const familiaView=await(await familia.cliente.request('/operacao/viagens/'+id)).json();
  assert.deepEqual(familiaView.alunos.map(x=>x.aluno_id),[a.id]);
  assert.equal((await outro.cliente.request('/operacao/viagens/'+id)).status,404);
  const agir=(acao,extra={},version=viagem.versao)=>motorista.cliente.request(`/operacao/viagens/${id}/acoes`,'POST',{versao:version,acao,...extra});
  assert.equal((await agir('PRESENCA',{alunoId:a.id,status:'PRESENTE'})).status,409);
  assert.equal((await agir('ENCERRAR')).status,409);
  const corridas=await Promise.all([agir('CHEGAR'),agir('CHEGAR')]);
  assert.deepEqual(corridas.map(r=>r.status).sort(),[200,409]);
  viagem=await corridas.find(r=>r.status===200).json();
  assert.equal((await agir('AVANCAR')).status,409);
  assert.equal((await agir('PRESENCA',{alunoId:b.id,status:'PRESENTE'})).status,409);
  const atualizar=async(acao,extra)=>{const r=await agir(acao,extra);assert.equal(r.status,200,await(r.status!==200?r.text():Promise.resolve('')));viagem=await r.json();};
  await atualizar('PRESENCA',{alunoId:a.id,status:'PRESENTE'});
  const primeiraEntrada=viagem.alunos.find(x=>x.aluno_id===a.id).entrada_em;
  await atualizar('PRESENCA',{alunoId:a.id,status:'PRESENTE'});
  assert.equal(viagem.alunos.find(x=>x.aluno_id===a.id).entrada_em,primeiraEntrada);
  await atualizar('PRESENCA',{alunoId:a.id,status:'AUSENTE'});
  assert.equal(viagem.alunos.find(x=>x.aluno_id===a.id).entrada_em,null);
  await atualizar('PRESENCA',{alunoId:a.id,status:'PRESENTE'});
  const alterado={...f.itinerario,paradas:f.itinerario.paradas.map(p=>({...p,local:'Local alterado'}))};
  assert.equal((await admin.request(`/rotas/${rota.id}/itinerario`,'PUT',alterado)).status,200);
  assert.equal((await(await motorista.cliente.request('/operacao/viagens/'+id)).json()).paradas[0].local,'Praça','Snapshot deve preservar itinerário original');
  await atualizar('AVANCAR');await atualizar('CHEGAR');await atualizar('PRESENCA',{alunoId:b.id,status:'AUSENTE'});await atualizar('AVANCAR');await atualizar('ENCERRAR');
  assert.equal(viagem.status,'ENCERRADA');assert.ok(viagem.alunos[0].saida_em);assert.equal(viagem.alunos[1].saida_em,null);
  assert.equal((await agir('CHEGAR')).status,409);
  const historico=await(await admin.request(`/operacao/historico?inicio=${data}&fim=${data}&rotaId=${rota.id}`)).json();
  assert.equal(historico.presentes,1);assert.equal(historico.ausentes,1);assert.equal(historico.frequencia,50);
  const meu=await(await familia.cliente.request(`/operacao/historico?inicio=${data}&fim=${data}`)).json();
  assert.ok(meu.presencas.every(p=>p.aluno_id===a.id));
  const eventos=await(await admin.request(`/operacao/viagens/${id}/eventos`)).json();
  assert.equal(eventos.filter(e=>e.acao==='CHEGAR').length,2);assert.ok(eventos.some(e=>e.detalhe==='PRESENTE -> AUSENTE'));
  const [inicioVolta,cancelamento]=await Promise.all([motorista.cliente.request('/operacao/viagens','POST',{rotaId:rota.id,trajeto:'VOLTA'}),confirmar(familiaB.cliente,b.id,'VOLTA','CANCELADO')]);
  assert.equal(inicioVolta.status,200);let volta=await inicioVolta.json();
  assert.equal(volta.alunos.some(x=>x.aluno_id===b.id),cancelamento.status===409,'Confirmação/início devem ser serializados');
  const acaoVolta=async(acao,extra={})=>{const r=await motorista.cliente.request(`/operacao/viagens/${volta.id}/acoes`,'POST',{versao:volta.versao,acao,...extra});assert.equal(r.status,200);volta=await r.json();};
  await acaoVolta('CHEGAR');for(const aluno of volta.alunos) await acaoVolta('PRESENCA',{alunoId:aluno.aluno_id,status:'PRESENTE'});await acaoVolta('AVANCAR');await acaoVolta('ENCERRAR');
  console.log('OK: vínculos, isolamento, agenda, capacidade, ida/volta, concorrência, snapshot, presença, correções, horários, auditoria e frequência.');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
