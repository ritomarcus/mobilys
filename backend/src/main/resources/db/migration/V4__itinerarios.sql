ALTER TABLE rotas ADD COLUMN versao_itinerario BIGINT NOT NULL DEFAULT 0;
CREATE TABLE paradas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_id BIGINT NOT NULL REFERENCES rotas(id) ON DELETE CASCADE,
    trajeto VARCHAR(5) NOT NULL CHECK (trajeto IN ('IDA', 'VOLTA')),
    ordem INTEGER NOT NULL CHECK (ordem > 0),
    local VARCHAR(150) NOT NULL CHECK (btrim(local) <> ''),
    referencia VARCHAR(250) NOT NULL DEFAULT '',
    horario TIME NOT NULL,
    tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('EMBARQUE', 'DESEMBARQUE', 'AMBOS')),
    CONSTRAINT uk_paradas_ordem UNIQUE (rota_id, trajeto, ordem) DEFERRABLE INITIALLY DEFERRED
);
